/** 关键词规则：按优先级排列，前面命中就停 */
var RULES = [
  [/曾/, '曾孙'],
  [/玄/, '玄孙'],
  [/来孙/, '来孙'],
  [/堂/, '堂'],
  [/表/, '表'],
  [/伯/, '伯'],
  [/叔/, '叔'],
  [/侄/, '侄'],
  [/甥/, '甥'],
  [/姑/, '姑'],
  [/舅/, '舅'],
  [/姨/, '姨'],
  [/岳/, '岳'],
  [/公公|婆婆/, '舅姑'],
  [/媳/, '儿媳'],
  [/婿/, '女婿'],
  [/嫂/, '嫂子'],
  [/外/, '外'],
  [/孙/, '孙'],
  [/祖父|祖母|爷爷|奶奶/, '祖']
];

function findKey(word) {
  if (LORE[word]) return word;
  return null;
}

function lookup(text) {
  if (!text) return null;
  var t = String(text).replace(/^你/, '');
  var segs = t.split('／').length > 1 ? [t.split('／')[0]] : [];
  var i, c;

  // 全词 / 第一个候选 / 去"远房"前缀
  for (i = 0; i < candidates(t).length; i++) {
    c = candidates(t)[i];
    var k = findKey(c) || findKey(c.replace(/^远房/, ''));
    if (k) return LORE[k];
  }

  // 含"的"的复合描述（你舅妈的妈妈、你侄女婿的爸爸）指向多个词，
  // 不能硬套单条典故
  if (t.indexOf('的') >= 0) return null;

  for (i = 0; i < RULES.length; i++) {
    if (RULES[i][0].test(t)) return LORE[RULES[i][1]];
  }
  return null;
}

function candidates(t) {
  var segs = t.split('／');
  return segs.length > 1 ? [t, segs[0]] : [t];
}

module.exports = {
  lookup: lookup,
  LORE: LORE
};
